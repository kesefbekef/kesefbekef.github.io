// "גזר" לא נתפס כ"גז", "אפליקציה" לא כ"אפל". מותר: אותיות שימוש לפני המילה (ב/ו/ה/ל/מ/ש/כ, גם "וה", "וב")
// וסיומת רבים/נקבה פשוטה אחריה ("גלידה" ← "גלידות", "צעצוע" ← "צעצועים")
const HEB = /[א-ת]/;
const reEsc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
// מילות מפתח שהן תחילת מילה בכוונה ("תרופ" ← תרופה/תרופות)
const STEMS = new Set(['תרופ', 'חולצ', 'מכנס', 'נעל', 'בגד']);
const WORD_END = '(?=$|[\\s),!?:;])';
export function normText(t) {
  return ' ' + String(t || '').toLowerCase().replace(/״/g, '"').replace(/[׳`]/g, "'").replace(/[-_.,/]/g, ' ').replace(/\s+/g, ' ').trim() + ' ';
}
function wordRe(w, { prefix = '[ובהלמשכ]{1,3}', suffix = true } = {}) {
  w = normText(w).trim();
  if (!w) return null;
  let body = reEsc(w);
  if (STEMS.has(w)) body += '[\\u05D0-\\u05EA]*';
  else if (suffix && HEB.test(w[w.length - 1])) {
    body = w.endsWith('ה') ? reEsc(w.slice(0, -1)) + '(?:ה|ות|ת)' : body + '(?:ים|ות|ה)?';
  }
  return new RegExp('(?:^|[\\s(])' + (HEB.test(w[0]) && prefix ? `(?:${prefix})?` : '') + body + WORD_END);
}

// כל מילות המפתח, הארוכות קודם — כדי ש"סופר פארם" ינצח את "סופר"
let KW = [];
function buildKW() {
  KW = Object.entries(CATS)
    .flatMap(([id, c]) => c.k.map(w => [normText(w).trim(), id]))
    .filter(([w]) => w)
    .sort((a, b) => b[0].length - a[0].length)
    .map(([w, id]) => [w, id, wordRe(w)]);
}
buildKW();

